#!/usr/bin/env python3
"""Generate the patched Renode CPU platforms caOS needs, from the installed Renode.

Renode's own models are not copied into the repo (no copy to keep in sync, no
Renode file redistributed): each run derives them from <renode>/platforms/cpus
and replaces the peripherals that break caOS (see CHANGES.md) with the stubs in
simu/platforms/adc_stub*.py. Output: simu/out/platforms/*_caos.repl.

usage: simu/gen_platforms.py [RENODE_ROOT]
RENODE_ROOT default: $RENODE_ROOT, else the folder of the `renode` on PATH
(portable package), else /opt/renode (.deb/.rpm package).
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLAT = os.path.join(HERE, 'platforms')
OUT = os.path.join(HERE, 'out', 'platforms')


def stub_entry(name, addr, stub, prefix=''):
    """A PythonPeripheral with the stub inlined (filename: is resolved against
    the Renode root, not this folder; inline scripts must not be indented).
    prefix: lines put before the stub (per-instance constants)."""
    body = prefix + open(os.path.join(PLAT, stub)).read().rstrip('\n')
    return (f"// caOS: register stub (source: simu/platforms/{stub})\n"
            f"{name}: Python.PythonPeripheral @ sysbus {addr}\n"
            f"    size: 0x400\n    initable: true\n    script: '''\n{body}\n'''\n\n")


def replace(src, start, end, new, what):
    a = src.find(start)
    b = src.find(end, a)
    if a < 0 or b < 0:
        sys.exit(f"gen_platforms: '{start}' not found in {what}: Renode version changed?")
    return src[:a] + new + src[b:]


def spi_pair(src, what):
    """SPI1 + SPI3 (F4/F7) as one master/slave pair (spi_pair_f4.py): Renode's
    STM32SPI has no slave mode, and ex29 wires SPI1 to SPI3."""
    for me, peer, addr, irq, nxt in (('spi1', 'spi3', '0x40013000', 35, 'spi2:'),
                                     ('spi3', 'spi1', '0x40003C00', 51, '\nspi4:' if 'spi4:' in src else 'i2c1:')):
        src = replace(src, f'{me}: SPI.STM32SPI', nxt.lstrip('\n'),
                      stub_entry(me, addr, 'spi_pair_f4.py',
                                 f"ME, PEER, IRQ = '{me}', '{peer}', {irq}\n"), what)
    return src


def renode_root():
    if len(sys.argv) > 1:
        return sys.argv[1]
    if os.environ.get('RENODE_ROOT'):
        return os.environ['RENODE_ROOT']
    exe = shutil.which('renode')
    if exe:
        d = os.path.dirname(os.path.realpath(exe))
        if os.path.isdir(os.path.join(d, 'platforms')):
            return d                        # portable: renode next to platforms/
    return '/opt/renode'


def main():
    root = renode_root()
    cpus = os.path.join(root, 'platforms', 'cpus')
    if not os.path.isdir(cpus):
        sys.exit(f"gen_platforms: no {cpus} (pass the Renode root or set RENODE_ROOT)")
    os.makedirs(OUT, exist_ok=True)

    def rd(n):
        return open(os.path.join(cpus, n)).read()

    hdr = "// GENERATED by simu/gen_platforms.py from Renode's {} - do not edit\n"

    # H753: stm32h7 + h743 (SysTick) + h753 (CRYP); ADC3 crashes on the TS channel
    h7 = replace(rd('stm32h7.repl'), 'adc3: Analog.STM32H7_ADC', 'bdma:',
                 stub_entry('adc3', '0x58026000', 'adc_stub.py'), 'stm32h7.repl')
    h743 = rd('stm32h743.repl').replace('using "platforms/cpus/stm32h7.repl"', '')
    h753 = rd('stm32h753.repl').replace('using "./stm32h743.repl"', '')
    write('stm32h753_caos.repl', hdr.format('stm32h7/h743/h753.repl') + h7 + h743 + h753)

    # F767: stm32f777; STM32_ADC divides by zero at end of conversion
    f7 = replace(rd('stm32f777.repl'), 'adc1: Analog.STM32_ADC', 'crc: CRC.STM32_CRC',
                 stub_entry('adc', '0x40012000', 'adc_stub_f4.py'), 'stm32f777.repl')
    f7 = spi_pair(f7, 'stm32f777.repl')
    write('stm32f777_caos.repl', hdr.format('stm32f777.repl') + f7)

    # F4: stm32f4 has no ADC (caOS polls SR.EOC for the banner temperature) and
    # no DWT (CYCCNT reads 0: tick calibration and CPU statistics go wrong)
    write('stm32f4_caos.repl', hdr.format('stm32f4.repl') + spi_pair(rd('stm32f4.repl'), 'stm32f4.repl') + '\n'
          + stub_entry('adc', '0x40012000', 'adc_stub_f4.py')
          + "// caOS: DWT (CYCCNT), missing in stm32f4.repl; F439/F446 run at 168 MHz\n"
            "dwt: Miscellaneous.DWT @ sysbus 0xE0001000\n    frequency: 168000000\n")

    expand_templates()


def expand_templates():
    """Our own platforms (no Renode model to start from): <name>.repl.in in
    simu/platforms, with @inline(stub.py) lines replaced by the stub source."""
    for n in sorted(os.listdir(PLAT)):
        if not n.endswith('.repl.in'):
            continue
        out = []
        for line in open(os.path.join(PLAT, n)).read().splitlines():
            s = line.strip()
            if s.startswith('@inline(') and s.endswith(')'):
                out.append(open(os.path.join(PLAT, s[8:-1])).read().rstrip('\n'))
            else:
                out.append(line)
        write(n[:-3], f"// GENERATED by simu/gen_platforms.py from simu/platforms/{n} - do not edit\n"
              + '\n'.join(out) + '\n')


def write(name, text):
    path = os.path.join(OUT, name)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        open(path, 'w').write(text)


if __name__ == '__main__':
    main()
