#!/usr/bin/env python3
"""
lookup_qa.py - questions and answers about the caOS API.

    tools/lookup_qa.py ca_mutex_lock        # every Q&A about that function
    tools/lookup_qa.py mutex timeout        # Q&A whose question or answer has ALL the words
    tools/lookup_qa.py -n 30 dma uart       # more results (default 10)
    tools/lookup_qa.py --type error ca_uart_put   # one kind: usage code parameters
                                                  # return error behavior hw_diff

The data is tools/db/caos_qa.jsonl: pairs generated by an AI from the API
reference. They explain the intent and the common mistakes, but they can be
wrong in the details: the signature in include/ (or tools/lookup_sym.py) is
the authority, and a function an answer names that lookup_sym.py does not
know does not exist.

Exit status: 0 something found, 1 nothing.
"""
import json
import sys
from pathlib import Path

DB = Path(__file__).resolve().parent / "db" / "caos_qa.jsonl"


def load():
    try:
        lines = DB.read_text(encoding="utf-8").splitlines()
    except FileNotFoundError:
        sys.exit(f"lookup_qa: {DB} not found")
    out = []
    for line in lines:
        if line.strip():
            r = json.loads(line)
            m = r["messages"]
            out.append((r.get("symbol", ""), r.get("type", ""), m[1]["content"], m[2]["content"]))
    return out


def main():
    args = sys.argv[1:]
    if not args or args[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    limit, qtype = 10, None
    while args and args[0] in ("-n", "--type"):
        if len(args) < 2:
            print(__doc__)
            return 1
        if args[0] == "-n":
            limit = int(args[1])
        else:
            qtype = args[1]
        args = args[2:]
    if not args:
        print(__doc__)
        return 1

    pairs = load()
    if qtype:
        pairs = [p for p in pairs if p[1] == qtype]
    if len(args) == 1 and args[0].startswith(("ca_", "CA_")):
        hits = [p for p in pairs if p[0] == args[0]]
        how = f"about {args[0]}"
        limit = max(limit, len(hits))          # a symbol: all of its pairs
    else:
        words = [w.lower() for w in args]
        hits = [p for p in pairs if all(w in (p[2] + " " + p[3]).lower() for w in words)]
        how = "with " + " ".join(args)

    for sym, t, q, a in hits[:limit]:
        print(f"--- {sym}  [{t}]")
        print(f"Q: {q}")
        print(f"A: {a}\n")
    if not hits:
        print(f"No Q&A {how}. Try fewer words, or tools/lookup_sym.py --find <words>.")
        return 1
    more = f" (first {limit}, -n to see more)" if len(hits) > limit else ""
    print(f"{len(hits)} pairs {how}{more}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
