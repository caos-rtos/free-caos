#ifndef CAOS_INFO_H
#define CAOS_INFO_H

#include "caos.h"

#if ENABLE_CLI && EN_CLI_CONFIG
/** One row of the CLI 'config' command: a number, or the macro's text. */
typedef struct {
    const char *name;   /* the symbol, as written in os_config.h / objmap.h */
    const char *text;   /* not NULL: printed as text (strings, function aliases) */
    u32         val;
} ca_cfg_row_t;

/**
 * @brief The rows of the 'config' command: the build configuration.
 * @details os_rows: every os_config.h symbol the project defines, in the
 *          config model's order (caos/src/os_config_table.inc, generated by
 *          tools/caos_config.py --gen-config-table: nothing is left out).
 *          board_rows: the board's values from objmap.h (MCU identity, clocks,
 *          MAX_TASK, stack sizes, USB endpoint map).
 *          Two builds are compared by diffing the 'config' text of each, or
 *          by @ref ca_caos_config_hash.
 * @warning Compiler flags (-O level, NDEBUG...) are not configuration: they
 *          belong to the build environment and are not in the rows.
 * @return  the number of os_rows; *n_board the number of board_rows.
 */
u16 ca_caos_config_rows(const ca_cfg_row_t **os_rows, const ca_cfg_row_t **board_rows,
                        u16 *n_board);


#if EN_SHA256
#define CA_CONFIG_HASH_LEN 32u   /* SHA-256 digest length */

/**
 * @brief SHA-256 fingerprint of the build configuration.
 *
 * @details Computes a SHA-256 digest (software, @ref ca_sha256) over the rows
 * of @ref ca_caos_config_rows - name and value of every os_config.h symbol
 * the project defines, then of the board's values (MCU identity included).
 * @c build_ver (git hash + timestamp) is not a row and does not enter it.
 *
 * Intended consequence: **two builds with the same configuration produce the
 * same hash**, even if compiled at different times or from different commits.
 * It changes only when a configuration choice (os_config.h / objmap.h) or the
 * MCU changes. Useful as a compact fingerprint to return over network/serial/
 * USB and compare between systems. For the detailed diff use the CLI command
 * @c config (text) with diff/meld.
 *
 * @param[out] digest buffer of at least @ref CA_CONFIG_HASH_LEN (32) bytes.
 * @note Compiler flags (-O, NDEBUG, ...) are not in the configuration and so
 *       do not enter the digest: they belong to the build environment.
 */
void ca_caos_config_hash(u8 *digest);
#endif /* EN_SHA256 */
#endif /* ENABLE_CLI && EN_CLI_CONFIG */

#endif /* CAOS_INFO_H */
