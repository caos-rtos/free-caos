"""PC counterpart of example 106 (JPEG codec).

  jpeg_check.py --gen          write jpeg_ref.h: JPEG files made by Pillow
                               (libjpeg) from the example's synthetic image,
                               and the PSNR the PC gets for each
                               configuration, encoded by Pillow and decoded
                               again - the reference the board is held to
  jpeg_check.py <capture>      the lines of 'jpeg dump': every JPEG the board
                               encoded is opened with Pillow, its header
                               checked, its PSNR against the same synthetic
                               image measured. Exit 0 = all good.

The synthetic image is integer arithmetic only, so the board and this
script draw the same pixels (ex106_image() in ca_os_ex106.c).
"""
import io
import math
import os
import re
import sys

from PIL import Image, JpegImagePlugin

HERE = os.path.dirname(os.path.abspath(__file__))
MARGIN_DB = 2.0     # board PSNR may be this much below the PC's

# name, width, height, subsampling, quality
#   css: 'gray', '444', '422', '420' (Pillow subsampling 0/1/2)
CASES = [
    ("gray_q90", 64, 48, "gray", 90),
    ("444_q90",  64, 48, "444",  90),
    ("422_q75",  64, 48, "422",  75),
    ("420_q90",  64, 48, "420",  90),
    ("420_q50",  64, 48, "420",  50),
    ("420_odd",  37, 23, "420",  90),
]
CSS_CODE = {"gray": 0, "444": 1, "422": 2, "420": 3}
PIL_SUB = {"444": 0, "422": 1, "420": 2}


def pixel(x, y, w, h):
    """ex106_image() in the firmware, pixel for pixel"""
    hsh = ((x * 73856093) ^ (y * 19349663)) & 0xFFFFFFFF
    hsh = (hsh * 2654435761) & 0xFFFFFFFF
    noise = ((hsh >> 28) & 15) - 8
    r = min(255, max(0, x * 255 // (w - 1) + noise))
    g = min(255, max(0, y * 255 // (h - 1) - noise))
    b = 200 if ((x // 8 + y // 8) & 1) else 40
    return r, g, b


def image(w, h, css):
    rgb = [pixel(x, y, w, h) for y in range(h) for x in range(w)]
    if css == "gray":
        im = Image.new("L", (w, h))
        im.putdata([(r * 3 + g * 6 + b) // 10 for r, g, b in rgb])
    else:
        im = Image.new("RGB", (w, h))
        im.putdata(rgb)
    return im


def psnr(a, b):
    pa, pb = a.tobytes(), b.tobytes()
    sse = sum((x - y) * (x - y) for x, y in zip(pa, pb))
    if sse == 0:
        return 99.99
    return 10.0 * math.log10(255.0 * 255.0 * len(pa) / sse)


def pil_encode(im, css, q):
    buf = io.BytesIO()
    if css == "gray":
        im.save(buf, "JPEG", quality=q, optimize=False, progressive=False)
    else:
        im.save(buf, "JPEG", quality=q, subsampling=PIL_SUB[css], optimize=False, progressive=False)
    return buf.getvalue()


def gen():
    out = ["/* Generated by jpeg_check.py --gen - do not edit.",
           " * JPEG files made by Pillow " + Image.__version__ + " from ex106_image(), and the",
           " * PSNR (x100) the PC measures decoding each one back. */",
           "", "#ifndef JPEG_REF_H", "#define JPEG_REF_H", ""]
    rows = []
    for name, w, h, css, q in CASES:
        src = image(w, h, css)
        data = pil_encode(src, css, q)
        back = Image.open(io.BytesIO(data))
        back.load()
        p = psnr(src, back.convert(src.mode))
        out.append("static const u8 s_ref_%s[%d] = {" % (name, len(data)))
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join("0x%02X" % c for c in data[i:i + 16]) + ",")
        out.append("};")
        rows.append('    { "%s", s_ref_%s, %d, %d, %d, %d, %d, %d },'
                    % (name, name, len(data), w, h, CSS_CODE[css], q, int(round(p * 100))))
        print("%-9s %5d bytes  PC PSNR %.2f dB" % (name, len(data), p))
    out += ["", "typedef struct {", "    const char *name;", "    const u8   *data;",
            "    u32         len;", "    u16         w, h;", "    u8          css, quality;",
            "    u16         pc_psnr;   /* dB x 100 */", "} ex106_ref_t;", "",
            "static const ex106_ref_t s_refs[] = {"] + rows + ["};", "", "#endif", ""]
    with open(os.path.join(HERE, "jpeg_ref.h"), "w") as f:
        f.write("\n".join(out))


def pc_psnr(css, q, w, h):
    src = image(w, h, css)
    back = Image.open(io.BytesIO(pil_encode(src, css, q)))
    back.load()
    return psnr(src, back.convert(src.mode))


def check(path):
    text = open(path, errors="replace").read()
    blocks = re.findall(r"JPG BEGIN (\S+) (\d+) (\d+) (\S+) (\d+) (\d+)\s*\n(.*?)JPG END", text, re.S)
    if not blocks:
        print("no 'JPG BEGIN' block in the capture")
        return 1
    bad = 0
    for name, w, h, css, q, n, body in blocks:
        w, h, q, n = int(w), int(h), int(q), int(n)
        hexs = re.sub(r"[^0-9A-Fa-f]", "", "".join(l.split(":", 1)[-1] for l in body.splitlines()))
        data = bytes.fromhex(hexs)[:n]
        why = ""
        try:
            im = Image.open(io.BytesIO(data))
            im.load()
        except Exception as e:      # noqa: BLE001 - any failure is the verdict
            print("%-9s %5d bytes  Pillow cannot open it: %s  BAD" % (name, len(data), e))
            bad += 1
            continue
        mode = "L" if css == "gray" else "RGB"
        if im.size != (w, h):
            why += " size %dx%d" % im.size
        if im.mode != mode:
            why += " mode %s" % im.mode
        if css != "gray":
            sub = JpegImagePlugin.get_sampling(im)
            if sub != PIL_SUB[css]:
                why += " subsampling %d" % sub
        p = psnr(image(w, h, css), im.convert(mode))
        ref = pc_psnr(css, q, w, h)
        if p < ref - MARGIN_DB:
            why += " PSNR %.2f < PC %.2f - %.1f" % (p, ref, MARGIN_DB)
        print("%-9s %5d bytes  %dx%d %s q%d  PSNR %.2f dB (PC encoder %.2f)  %s"
              % (name, len(data), w, h, css, q, p, ref, ("BAD:" + why) if why else "ok"))
        if why:
            bad += 1
    print("JPEG PC CHECK %s (%d/%d)" % ("PASS" if bad == 0 else "FAIL", len(blocks) - bad, len(blocks)))
    return 0 if bad == 0 else 1


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "--gen":
        gen()
        sys.exit(0)
    if len(sys.argv) == 2:
        sys.exit(check(sys.argv[1]))
    print(__doc__)
    sys.exit(2)
