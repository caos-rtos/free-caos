#!/usr/bin/env python3
"""
test_tftp_ncm.py  -  DHCP + TFTP server for caOS example_82

example_82 boots a DHCP client (DORA) and only then accepts TFTP commands,
so the PC must act as DHCP server first. Pass --iface to set up the network
(IP + dnsmasq) exactly like example_35's test_dhcp_pc.sh, then serve TFTP.

Usage:
    # All-in-one: configure iface, run DHCP (dnsmasq) + TFTP server
    sudo python3 test_tftp_ncm.py --iface eth0 --file test.bin --size 10000

    # TFTP only (board already has an IP, e.g. static or external DHCP)
    sudo python3 test_tftp_ncm.py --bind 0.0.0.0 --file test.bin --size 8192

    # Then, from the caOS CLI on the board:
    #   tftp get <pc_ip> test.bin      (pc_ip = 192.168.10.1 with --iface)

The script:
  1. (--iface) Assigns 192.168.10.1/24 to the iface and starts dnsmasq as
     DHCP server (pool 192.168.10.100-200), cleaning up on exit.
  2. Generates a test file of <size> bytes with a known pattern
  3. Runs a minimal TFTP server (RFC 1350, octet mode, RRQ + optional WRQ)
  4. After each transfer, prints stats (blocks, time, throughput)

Options:
    --iface  network interface to configure as DHCP server (e.g. eth0, enp6s0)
    --pc-ip  PC/server IP when using --iface (default 192.168.10.1)
    --bind   IP to bind the TFTP server on (default 0.0.0.0)
    --port   TFTP port (default 69, requires root/sudo)
    --file   filename the board will request (default test.bin)
    --size   file size in bytes to serve (default 8192)
    --put    also serve as a WRQ target (save incoming file to <file>_recv.bin)
"""

import argparse
import atexit
import shutil
import signal
import socket
import struct
import subprocess
import time
import os

BLOCK_SIZE = 512

# --- DHCP (dnsmasq) defaults, mirroring example_35/test_dhcp_pc.sh -----------
DHCP_START = "192.168.10.100"
DHCP_END   = "192.168.10.200"
DHCP_MASK  = "255.255.255.0"
DHCP_LEASE = "1h"
DNSMASQ_CONF = "/tmp/dnsmasq-caos-ex82.conf"
DNSMASQ_PID  = "/tmp/dnsmasq-caos-ex82.pid"
DNSMASQ_LOG  = "/tmp/dnsmasq-caos-ex82.log"

NCM_MAC_PREFIX = "02:ca:05"   # host-side MAC announced by the NCM descriptors


def find_ncm_iface(timeout_s: int = 30):
    """Find the USB-NCM interface by MAC, waiting for it to show up.

    The interface is born with USB enumeration, so it may not exist yet when
    this script starts: retry for timeout_s seconds.
    ORDER: board FIRST, then this script.
    """
    net_dir = "/sys/class/net"
    for _ in range(timeout_s):
        try:
            for name in os.listdir(net_dir):
                if name == "lo":
                    continue
                try:
                    with open(os.path.join(net_dir, name, "address")) as f:
                        if f.read().strip().lower().startswith(NCM_MAC_PREFIX):
                            return name
                except OSError:
                    continue
        except OSError:
            pass
        time.sleep(1)
    return None

OP_RRQ   = 1
OP_WRQ   = 2
OP_DATA  = 3
OP_ACK   = 4
OP_ERROR = 5


def make_test_data(size: int) -> bytes:
    """Generate a repeating pattern: 0x00, 0x01, ..., 0xFF, 0x00, ..."""
    pattern = bytes(range(256))
    reps, rem = divmod(size, 256)
    return pattern * reps + pattern[:rem]


# ---------------------------------------------------------------------------
# DHCP server (dnsmasq) - same network setup as example_35/test_dhcp_pc.sh
# ---------------------------------------------------------------------------
def _run(cmd, check=False):
    return subprocess.run(cmd, check=check,
                          stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def dhcp_stop(iface: str, pc_ip: str):
    """Kill dnsmasq and remove the IP from the interface."""
    if os.path.exists(DNSMASQ_PID):
        try:
            with open(DNSMASQ_PID) as f:
                os.kill(int(f.read().strip()), signal.SIGTERM)
        except (ProcessLookupError, ValueError, OSError):
            pass
        try:
            os.remove(DNSMASQ_PID)
        except OSError:
            pass
    else:
        _run(["pkill", "-f", "dnsmasq-caos-ex82"])
    _run(["ip", "addr", "del", f"{pc_ip}/24", "dev", iface])
    print(f"[*] DHCP stopped, {iface} restored.")


def dhcp_start(iface: str, pc_ip: str):
    """Assign pc_ip/24 to iface and start dnsmasq as DHCP server."""
    dnsmasq = shutil.which("dnsmasq") or "/usr/sbin/dnsmasq"
    if not os.path.exists(dnsmasq):
        raise SystemExit("[!] dnsmasq not found - install it or run without --iface")
    if _run(["ip", "link", "show", iface]).returncode != 0:
        raise SystemExit(f"[!] interface {iface} not found")

    print(f"[*] Configuring {iface} -> {pc_ip}/{DHCP_MASK}")
    _run(["ip", "addr", "flush", "dev", iface])
    _run(["ip", "addr", "add", f"{pc_ip}/24", "dev", iface], check=True)
    _run(["ip", "link", "set", iface, "up"], check=True)

    with open(DNSMASQ_CONF, "w") as f:
        f.write(
            "# dnsmasq config for caOS ex82 - generated by test_tftp_ncm.py\n"
            f"interface={iface}\n"
            "bind-interfaces\n"
            "except-interface=lo\n"
            f"dhcp-range={DHCP_START},{DHCP_END},{DHCP_MASK},{DHCP_LEASE}\n"
            f"dhcp-option=option:router,{pc_ip}\n"
            "dhcp-option=option:dns-server,8.8.8.8\n"
            f"dhcp-option=option:netmask,{DHCP_MASK}\n"
            "log-dhcp\n"
            "no-resolv\n"
            "no-hosts\n"
        )
    if os.path.exists(DNSMASQ_LOG):
        os.remove(DNSMASQ_LOG)
    print(f"[*] Starting dnsmasq (pool {DHCP_START} - {DHCP_END})")
    _run([dnsmasq, "-C", DNSMASQ_CONF,
          f"--pid-file={DNSMASQ_PID}", f"--log-facility={DNSMASQ_LOG}"], check=True)
    print(f"[*] dnsmasq up - DHCP log: tail -f {DNSMASQ_LOG}")
    print(f"[*] Board should print 'DHCP BOUND'; serve TFTP with: "
          f"tftp get {pc_ip} <file>\n")


def hexdump(buf: bytes, max_lines: int = 16):
    """Print up to max_lines of 'hexdump -C'-style output."""
    for off in range(0, min(len(buf), max_lines * 16), 16):
        row = buf[off:off + 16]
        hexs = ' '.join(f'{b:02x}' for b in row)
        ascii_ = ''.join(chr(b) if 32 <= b < 127 else '.' for b in row)
        print(f'{off:08x}: {hexs:<47}  {ascii_}')


def send_error(sock, addr, code: int, msg: str):
    pkt = struct.pack('!HH', OP_ERROR, code) + msg.encode() + b'\x00'
    sock.sendto(pkt, addr)


def handle_rrq(sock, client_addr, data_buf: bytes, timeout: float, retry_n: int):
    """Handle a GET (RRQ) request: send data_buf to client."""
    total = len(data_buf)
    n_blocks = (total + BLOCK_SIZE - 1) // BLOCK_SIZE or 1
    print(f"[RRQ] client={client_addr}  total={total}B  blocks={n_blocks}")

    block = 1
    offset = 0
    t_start = time.time()

    # Loop until a SHORT block (< 512B) is sent and ACKed. If total is a
    # multiple of 512, the final iteration sends a 0-byte block to mark EOF
    # (RFC 1350), which the caOS client waits for.
    while True:
        chunk = data_buf[offset:offset + BLOCK_SIZE]
        pkt = struct.pack('!HH', OP_DATA, block) + chunk
        acked = False

        for attempt in range(retry_n + 1):
            sock.sendto(pkt, client_addr)
            sock.settimeout(timeout)
            try:
                resp, addr = sock.recvfrom(1024)
                op, blk = struct.unpack_from('!HH', resp)
                if op == OP_ACK and blk == block:
                    acked = True
                    break
                if op == OP_ERROR:
                    code, = struct.unpack_from('!H', resp, 2)
                    msg = resp[4:].rstrip(b'\x00').decode(errors='replace')
                    print(f"[ERROR] code={code} msg={msg}")
                    return
            except socket.timeout:
                print(f"  timeout block={block} attempt={attempt+1}")

        if not acked:
            print(f"[FAIL] block={block} not ACKed after {retry_n} retries")
            return

        offset += len(chunk)
        if len(chunk) < BLOCK_SIZE:
            break
        block += 1

    elapsed = time.time() - t_start
    if elapsed > 0:
        mbps = (total / elapsed) / 1_000_000
        print(f"[OK] {total}B in {elapsed:.2f}s  ({mbps:.2f} MB/s)")
    else:
        print(f"[OK] {total}B")


def handle_wrq(sock, client_addr, save_path: str, timeout: float, retry_n: int):
    """Handle a PUT (WRQ) request: receive data from client."""
    print(f"[WRQ] client={client_addr}  save_to={save_path}")

    # Send ACK 0
    ack0 = struct.pack('!HH', OP_ACK, 0)
    sock.sendto(ack0, client_addr)

    received = bytearray()
    expected = 1
    t_start = time.time()

    while True:
        sock.settimeout(timeout)
        try:
            pkt, addr = sock.recvfrom(4 + BLOCK_SIZE + 16)
        except socket.timeout:
            print("[FAIL] timeout waiting for DATA")
            return

        op, blk = struct.unpack_from('!HH', pkt)
        if op == OP_ERROR:
            print("[ERROR] client sent ERROR")
            return

        if op != OP_DATA or blk != expected:
            continue

        chunk = pkt[4:]
        received.extend(chunk)
        ack = struct.pack('!HH', OP_ACK, blk)
        sock.sendto(ack, client_addr)

        if len(chunk) < BLOCK_SIZE:
            break
        expected += 1

    elapsed = time.time() - t_start
    with open(save_path, 'wb') as f:
        f.write(received)
    print(f"[OK] received {len(received)}B in {elapsed:.2f}s -> {save_path}")
    print("--- first 256 bytes ---")
    hexdump(received, 16)


def run_server(bind_ip: str, port: int, filename: str, data_buf: bytes,
               allow_put: bool, timeout: float, retry_n: int):
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.bind((bind_ip, port))
    print(f"TFTP server listening on {bind_ip}:{port}")
    print(f"Serving '{filename}' ({len(data_buf)}B) - Ctrl-C to stop")
    print()

    while True:
        sock.settimeout(None)
        try:
            pkt, client_addr = sock.recvfrom(1024)
        except KeyboardInterrupt:
            print("\nServer stopped.")
            break

        op = struct.unpack_from('!H', pkt)[0]
        # parse filename from request
        rest = pkt[2:]
        parts = rest.split(b'\x00')
        req_file = parts[0].decode(errors='replace') if parts else ''
        mode     = parts[1].decode(errors='replace').lower() if len(parts) > 1 else ''

        if op == OP_RRQ:
            if req_file != filename:
                print(f"[WARN] RRQ for unknown file '{req_file}' - serving anyway")
            if mode != 'octet':
                send_error(sock, client_addr, 0, "only octet mode supported")
                continue
            # Use a new socket for the transfer (separate TID)
            tx_sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            tx_sock.bind(('', 0))
            handle_rrq(tx_sock, client_addr, data_buf, timeout, retry_n)
            tx_sock.close()

        elif op == OP_WRQ:
            if not allow_put:
                send_error(sock, client_addr, 2, "PUT not enabled")
                continue
            save_path = req_file + '_recv.bin'
            rx_sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
            rx_sock.bind(('', 0))
            handle_wrq(rx_sock, client_addr, save_path, timeout, retry_n)
            rx_sock.close()

        else:
            send_error(sock, client_addr, 4, "illegal operation")

    sock.close()


def main():
    ap = argparse.ArgumentParser(description='caOS DHCP + TFTP test server')
    ap.add_argument('--iface',   default='auto',
                    help="NCM iface for the DHCP server ('auto' = detect by MAC 02:ca:05, the default; '' to skip)")
    ap.add_argument('--pc-ip',   default='192.168.10.1',
                    help='PC/server IP when using --iface (default 192.168.10.1)')
    ap.add_argument('--bind',    default='0.0.0.0')
    ap.add_argument('--port',    type=int, default=69)
    ap.add_argument('--file',    default='test.bin')
    ap.add_argument('--size',    type=int, default=8192)
    ap.add_argument('--put',     action='store_true', help='accept WRQ uploads')
    ap.add_argument('--no-dhcp', action='store_true',
                    help='serve TFTP only - leave DHCP to whoever already '
                         'runs it. The test bench passes this: it has its own '
                         'dnsmasq on the board link, and two DHCP servers on '
                         'one subnet break the client, they do not share it.')
    ap.add_argument('--timeout', type=float, default=5.0)
    ap.add_argument('--retry',   type=int, default=3)
    args = ap.parse_args()

    # --no-dhcp wins over the 'auto' default: the interface lookup exists only
    # to hand dhcp_start() a name, so with DHCP off there is nothing to look up.
    #
    # This default is why ex82 failed inside a full bench round and passed on
    # its own. The ETH twin (example_49) defaults --iface to None, so run
    # without arguments it serves TFTP and nothing else; this one defaults to
    # 'auto', so it ALWAYS brought up a dnsmasq of its own - next to the one the
    # bench had already moved onto the board's link. The board took the bench's
    # offer (192.168.10.81, pool .50-.99), broadcast the REQUEST, and this
    # script's dnsmasq NAKed it for being outside .100-.200. The client went
    # back to INIT and stayed at 0.0.0.0, and the bench's lease file stayed
    # empty because the handshake never completed.
    if args.no_dhcp:
        args.iface = None
    elif args.iface == "auto":
        print("[*] Looking for the USB-NCM interface (MAC 02:ca:05:*)...")
        args.iface = find_ncm_iface()
        if args.iface is None:
            raise SystemExit("[!] no NCM interface found in 30s - is the board "
                             "powered and enumerated? (dmesg | tail)")
        print(f"[*] NCM interface: {args.iface}")

    if args.iface:
        if os.geteuid() != 0:
            raise SystemExit("[!] --iface requires root (use sudo)")
        dhcp_start(args.iface, args.pc_ip)
        atexit.register(dhcp_stop, args.iface, args.pc_ip)

    data = make_test_data(args.size)
    print(f"Generated {len(data)}B test pattern")

    try:
        run_server(args.bind, args.port, args.file, data,
                   args.put, args.timeout, args.retry)
    except KeyboardInterrupt:
        print("\nServer stopped.")


if __name__ == '__main__':
    main()
