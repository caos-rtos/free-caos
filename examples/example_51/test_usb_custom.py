#!/usr/bin/env python3
"""
test_usb_custom.py - loopback test for example_51 (USB management + custom class)

The device is built by the ca_usb_mng stack with the custom service:
    VID=0xCA01  PID=0x0001   (PID = USB_PID_BASE_CUSTOM + ep_data = 0 + 1)
    1 vendor interface 0xFF, 1 bulk IN EP (0x81) + 1 bulk OUT EP (0x01)

Checks:
    1. the device enumerates (descriptors generated by the mgmt)
    2. bulk loopback EP1: every OUT packet comes back identical on IN

Usage:
    sudo python3 test_usb_custom.py [--packets N] [--size B]
"""

import usb.core
import usb.util
import argparse
import sys
import random
import time
import threading
import queue

VID     = 0xCA01
PID     = 0x0001
TIMEOUT = 2000   # ms
FW_DEPTH = 32    # firmware EP1 RX queue depth

def find_device(retries=5):
    for attempt in range(retries):
        dev = usb.core.find(idVendor=VID, idProduct=PID)
        if dev is not None:
            print(f"Found: bus {dev.bus} dev {dev.address}")
            return dev
        if attempt < retries - 1:
            time.sleep(0.5)
    print(f"Device {VID:04x}:{PID:04x} not found")
    sys.exit(1)

def dump_descriptors(dev):
    print(f"  idVendor=0x{dev.idVendor:04x} idProduct=0x{dev.idProduct:04x}")
    cfg = dev.get_active_configuration()
    intf = cfg[(0, 0)]
    print(f"  bInterfaceClass=0x{intf.bInterfaceClass:02x} "
          f"bNumEndpoints={intf.bNumEndpoints}")
    for ep in intf:
        d = "IN" if (ep.bEndpointAddress & 0x80) else "OUT"
        print(f"    EP 0x{ep.bEndpointAddress:02x} {d} "
              f"type={usb.util.endpoint_type(ep.bmAttributes)} "
              f"mps={ep.wMaxPacketSize}")

def flush_ep_in(dev, ep_in, pkt_size, timeout_ms=300):
    drained = 0
    while True:
        try:
            dev.read(ep_in, pkt_size, timeout_ms)
            drained += 1
        except usb.core.USBError:
            break
    if drained:
        print(f"  [flush] drained {drained} stale packet(s)")

def test_loopback(dev, num_packets, pkt_size):
    try:
        dev.set_configuration(1)
    except usb.core.USBError as e:
        if e.errno not in (16,):    # 16 = busy (already configured)
            print(f"set_configuration: {e}")

    ep_out = 0x01
    ep_in  = 0x81
    flush_ep_in(dev, ep_in, pkt_size)

    print(f"Loopback EP1 x {num_packets} packets x {pkt_size} bytes "
          f"[writer+reader paralleli]...")

    corr_q = queue.Queue(maxsize=max(1, FW_DEPTH - 1))
    ok = [0]; err = [0]

    def writer():
        try:
            for _ in range(num_packets):
                data = bytes(random.randint(0, 255) for _ in range(pkt_size))
                dev.write(ep_out, data, TIMEOUT)
                corr_q.put(data)
        except Exception as e:
            print(f"writer error: {e}")
            corr_q.put(None)

    def reader():
        received = 0
        while received < num_packets:
            expected = corr_q.get()
            if expected is None:
                break
            try:
                rx = bytes(dev.read(ep_in, pkt_size, TIMEOUT))
                if rx == expected:
                    ok[0] += 1
                else:
                    err[0] += 1
                    if err[0] <= 3:
                        print(f"MISMATCH sent={expected[:4].hex()} got={rx[:4].hex()}")
            except usb.core.USBError as e:
                err[0] += 1
                if err[0] <= 3:
                    print(f"rx error: {e}")
            received += 1

    t0 = time.time()
    wt = threading.Thread(target=writer, daemon=True)
    rt = threading.Thread(target=reader, daemon=True)
    wt.start(); rt.start(); wt.join(); rt.join()
    elapsed = time.time() - t0

    total_bytes = ok[0] * pkt_size
    rate = total_bytes / elapsed / 1024 / 1024 if elapsed > 0 else 0
    print(f"\nEP1: {ok[0]}/{num_packets} OK  {err[0]} err")
    print(f"Throughput: {rate:.3f} MB/s ({total_bytes/1024:.1f} KB in {elapsed:.2f}s)")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--packets", type=int, default=10000)
    ap.add_argument("--size",    type=int, default=64)
    args = ap.parse_args()

    dev = find_device()
    print("Descriptors (generated by ca_usb_mng):")
    dump_descriptors(dev)
    test_loopback(dev, args.packets, args.size)

if __name__ == "__main__":
    main()
